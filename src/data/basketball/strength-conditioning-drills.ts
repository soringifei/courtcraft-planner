import type {
  AgeGroupId,
  CourtDiagram,
  Drill,
  DrillCategory,
  Intensity,
  PhysicalQuality,
  PracticePlacement,
  TrainingCategoryId,
} from "./types";

type StrengthDrillSeed = {
  id: string;
  title: string;
  ageGroups: AgeGroupId[];
  durationMin: number;
  intensity: Intensity;
  categoryTags: TrainingCategoryId[];
  physicalQualities: PhysicalQuality[];
  practicePlacement: PracticePlacement[];
  equipment: string[];
  objective: string;
  pattern: string;
  setupDetail: string;
  executionDetail: string;
  cue: string;
  mistake: string;
  regression: string;
  progression: string;
  scoring: string;
  safetyNote: string;
  basketballTransfer: string;
};

function strengthCategory(tags: TrainingCategoryId[]): DrillCategory {
  if (tags.includes("conditioning")) return "conditioning";
  if (tags.includes("defense")) return "defense";
  return "movement";
}

function diagram(seed: StrengthDrillSeed): CourtDiagram {
  const lineType = seed.physicalQualities.includes("reactive_agility")
    ? "defensive_slide"
    : seed.physicalQualities.includes("deceleration")
      ? "cut"
      : seed.categoryTags.includes("conditioning")
        ? "rotation"
        : "defensive_slide";

  return {
    mode: "half",
    players: [
      { id: "a", label: "A", role: "neutral", x: 22, y: 76 },
      { id: "b", label: "B", role: "neutral", x: 78, y: 76 },
      { id: "c", label: "C", role: "coach", x: 50, y: 42 },
    ],
    cones: [
      { id: "start", x: 22, y: 76, label: "start" },
      { id: "mid", x: 50, y: 54, label: "change" },
      { id: "finish", x: 78, y: 34, label: "finish" },
    ],
    spots: [
      { id: "stick", x: 50, y: 54, label: "stick" },
      { id: "recover", x: 42, y: 28, label: "recover" },
    ],
    lines: [
      {
        id: "line-1",
        type: lineType,
        from: { x: 22, y: 76 },
        to: { x: 50, y: 54 },
        label: seed.pattern,
      },
      {
        id: "line-2",
        type: seed.categoryTags.includes("conditioning") ? "rotation" : "cut",
        from: { x: 50, y: 54 },
        to: { x: 78, y: 34 },
        label: "transfer",
      },
    ],
    zones: [
      { id: "work-zone", label: "movement lane", x: 15, y: 25, width: 70, height: 56 },
    ],
  };
}

function buildStrengthDrill(seed: StrengthDrillSeed): Drill {
  return {
    id: seed.id,
    title: seed.title,
    category: strengthCategory(seed.categoryTags),
    ageGroups: seed.ageGroups,
    durationMin: seed.durationMin,
    intensity: seed.intensity,
    playersMin: 2,
    playersMax: 16,
    equipment: seed.equipment,
    courtMode: "half",
    objective: seed.objective,
    setup: [
      seed.setupDetail,
      "Use clear start, change, and finish markers so players understand the path before speed increases.",
      "Keep groups small enough that every rep can be coached for posture, stopping quality, and control.",
    ],
    execution: [
      seed.executionDetail,
      "Players complete short reps, rotate quickly, and return through a walking recovery lane.",
      "Coach stops the group immediately if posture, landing control, or spacing breaks down.",
      `Finish each set by naming the basketball action it supports: ${seed.basketballTransfer}`,
    ],
    coachingCues: [
      seed.cue,
      "Push the floor, then regain balance before the next change of direction.",
      "Quality beats speed; a clean stop or turn is worth more than a fast unstable rep.",
    ],
    commonMistakes: [
      seed.mistake,
      "Players drift upright during the change; cue lower hips and quiet shoulders.",
      "Players crowd the lane; widen the cones or reduce the number of active athletes.",
    ],
    regression: seed.regression,
    progression: seed.progression,
    scoring: seed.scoring,
    safetyNote: seed.safetyNote,
    diagram: diagram(seed),
    categoryTags: seed.categoryTags,
    trainingDomain: "strength_conditioning",
    physicalQualities: seed.physicalQualities,
    practicePlacement: seed.practicePlacement,
    basketballTransfer: seed.basketballTransfer,
  };
}

